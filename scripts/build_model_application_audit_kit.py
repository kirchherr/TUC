class AuditKitError(ValueError):
    """Closed diagnostic; a rejected build emits no success checksum."""

    def __init__(self) -> None:
        super().__init__("model_application_audit_kit_rejected")


def _git_executable(repo: Path) -> str:
    # Never let Windows' current-directory lookup or a checkout-local PATH
    # entry turn a source file named git/git.exe into an executed program.
    name = "git.exe" if os.name == "nt" else "git"
    for entry in os.get_exec_path():
        directory = Path(entry)
        if not directory.is_absolute() or directory.is_relative_to(repo):
            continue
        try:
            directory = directory.resolve(strict=True)
            if directory.is_relative_to(repo):
                continue
            program = (directory / name).resolve(strict=True)
            if (
                not program.is_relative_to(repo)
                and program.is_file() and os.access(program, os.X_OK)
            ):
                return str(program)
        except (OSError, RuntimeError):
            continue
    raise AuditKitError()


def _git(repo: Path, *args: str) -> bytes:
    # Read the requested repository, without inherited alternate directories,
    # replacement objects, tracing, pager commands or interactive prompts.
    environment = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    environment.update(
        GIT_NO_REPLACE_OBJECTS="1", GIT_TERMINAL_PROMPT="0", GIT_OPTIONAL_LOCKS="0"
    )
    result = subprocess.run(
        [_git_executable(repo), "--no-pager", "--literal-pathspecs",
         "-c", f"safe.directory={repo}",
         "-C", str(repo), *args],
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
        env=environment, timeout=15, check=False,
    )
    if result.returncode:
        raise AuditKitError()
    return result.stdout


def _snapshot(repo: Path) -> tuple[str, dict[str, bytes]]:
    head = _git(repo, "rev-parse", "--verify", "HEAD").strip()
    if _SHA1.fullmatch(head) is None:
        raise AuditKitError()
    revision = head.decode("ascii")
    listing = _git(repo, "ls-tree", "-z", revision, "--", *SOURCE_FILES.values())
    if len(listing) > 4096:
        raise AuditKitError()
    objects: dict[str, str] = {}
    for entry in listing.split(b"\0"):
        if not entry:
            continue
        metadata, object_path = entry.split(b"\t", 1)
        mode, kind, blob_oid = metadata.split(b" ")
        name = object_path.decode("ascii")
        if (
            name not in SOURCE_FILES.values() or name in objects
            or mode not in (b"100644", b"100755") or kind != b"blob"
            or _SHA1.fullmatch(blob_oid) is None
        ):
            raise AuditKitError()
        objects[name] = blob_oid.decode("ascii")
    if set(objects) != set(SOURCE_FILES.values()):
        raise AuditKitError()
    payloads: dict[str, bytes] = {}
    for member, relative_path in SOURCE_FILES.items():
        object_id = objects[relative_path]
        size = _git(repo, "cat-file", "-s", object_id).strip()
        if len(size) > 20 or not size.isdigit() or not 0 < int(size) <= MAX_SOURCE_BYTES:
            raise AuditKitError()
        data = _git(repo, "cat-file", "blob", object_id)
        if len(data) != int(size):
            raise AuditKitError()
        payloads[member] = data
    return revision, payloads


def build_audit_kit(repo: Path, output: Path) -> str:
    """Create a fixed-member ZIP from one committed Git snapshot, exclusively."""
    try:
        if (
            _OUTPUT_NAME.fullmatch(output.name) is None
            or output.exists() or output.is_symlink() or output.parent.is_symlink()
        ):
            raise AuditKitError()
        parent = output.parent.resolve(strict=True)
        if not parent.is_dir():
            raise AuditKitError()
        revision, payloads = _snapshot(repo.resolve(strict=True))
        payloads["README.md"] = _README
        payloads["SOURCE.txt"] = f"source_commit={revision}\n".encode("ascii")
        payloads["CHECKSUMS.sha256"] = "".join(
            f"{sha256(data).hexdigest()}  {name}\n" for name, data in sorted(payloads.items())
        ).encode("ascii")
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_STORED, allowZip64=False) as kit:
            for name, data in sorted(payloads.items()):
                info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
                info.create_system = 3
                info.external_attr = (stat.S_IFREG | 0o644) << 16
                info.compress_type = zipfile.ZIP_STORED
                kit.writestr(info, data)
        contents = buffer.getvalue()
        if len(contents) > MAX_ARCHIVE_BYTES:
            raise AuditKitError()
        # Exclusive creation also rejects a file/symlink created after the check.
        with (parent / output.name).open("xb") as stream:
            stream.write(contents)
        return sha256(contents).hexdigest()
    except (OSError, ValueError, UnicodeError, RuntimeError, subprocess.SubprocessError):
        raise AuditKitError() from None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        digest = build_audit_kit(Path(__file__).resolve().parents[1], args.output)
    except AuditKitError:
        parser.exit(2, "model_application_audit_kit_rejected\n")
    print(f"{digest}  {args.output.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
